-- Publications, their Files, and the Import jobs that bring Files in (spec §3, §5).

CREATE TABLE publication (
    -- BY DEFAULT: the import reserves the id before copying, because the folder name contains it.
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind        TEXT        NOT NULL CHECK (kind IN ('prose', 'comic')),
    title       TEXT        NOT NULL,
    sort_title  TEXT        NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    trashed_at  TIMESTAMPTZ
);

CREATE TABLE file (
    id              BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    publication_id  BIGINT      NOT NULL REFERENCES publication (id),
    format          TEXT        NOT NULL CHECK (format IN ('epub', 'pdf', 'cbz', 'cbr')),
    size            BIGINT      NOT NULL,
    sha256          CHAR(64)    NOT NULL UNIQUE,
    partial_md5     CHAR(32)    NOT NULL,
    role            TEXT        NOT NULL CHECK (role IN ('original', 'conversion')),
    derived_from    BIGINT      REFERENCES file (id),
    page_count      INT,
    stored_path     TEXT        NOT NULL UNIQUE,
    imported_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    trashed_at      TIMESTAMPTZ
);

CREATE INDEX file_publication_idx ON file (publication_id);
CREATE INDEX file_partial_md5_idx ON file (partial_md5);

CREATE TABLE import_job (
    id              BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    source          TEXT        NOT NULL CHECK (source IN ('inbox', 'upload')),
    original_name   TEXT        NOT NULL,
    kind_hint       TEXT        CHECK (kind_hint IN ('prose', 'comic')),
    state           TEXT        NOT NULL DEFAULT 'pending'
                                CHECK (state IN ('pending', 'processing', 'done', 'skipped', 'failed')),
    reason          TEXT,
    warnings        TEXT[]      NOT NULL DEFAULT '{}',
    -- Where the store stage is copying the File, so an interrupted copy can be cleaned up.
    store_target    TEXT,
    publication_id  BIGINT      REFERENCES publication (id),
    file_id         BIGINT      REFERENCES file (id),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX import_job_state_idx ON import_job (state, id);
